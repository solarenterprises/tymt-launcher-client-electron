const ensureExistDir = async (dirPath: string) => {
  try {
    const stats = await fs.stat(dirPath);
    if (!stats.isDirectory()) {
      throw new Error(`${dirPath} exists but is not a directory`);
    }
  } catch (error) {
    if (error.code === "ENOENT") {
      await fs.mkdir(dirPath, { recursive: true });
    } else {
      throw error;
    }
  }
};

const extractAsync = (fileLocation: string, installDir: string) =>
  new Promise((resolve, reject) => {
    const zip = new admZip(fileLocation);
    zip.extractAllToAsync(installDir, true, false, (err) => {
      if (err) {
        reject(err);
      } else {
        resolve(true);
      }
    });
  });

const execAsync = (command: string, options?: ExecOptions) =>
  new Promise((resolve, reject) => {
    exec(command, options, (error, stdout, stderr) => {
      if (error) reject(stderr);
      else resolve(stdout);
    });
  });

