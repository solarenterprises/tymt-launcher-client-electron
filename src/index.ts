const createWindow = (): void => {
  // Create the browser window.
  const mainWindow = new BrowserWindow({
    height: 800,
    width: 1200,
    webPreferences: {
      preload: MAIN_WINDOW_PRELOAD_WEBPACK_ENTRY,
      // devTools: !app.isPackaged, // Enable/Disable devTools
    },
  });

  mainWindow.setIcon("src/assets/main/NewLogoHead.png");

  // and load the index.html of the app.
  mainWindow.loadURL(MAIN_WINDOW_WEBPACK_ENTRY);

  // Open the DevTools.
  mainWindow.webContents.openDevTools();

  // Get CPU information
  const cpuArch = os.arch();
  const cpuType = os.cpus()[0].model;
  const osType = os.type();

  // Send CPU information to renderer process
  mainWindow.webContents.on("did-finish-load", () => {
    mainWindow.webContents.send("sys-info", { cpuArch: cpuArch, cpuType: cpuType, osType: osType });
  });
};

const openWindow = () => {
  const windows = BrowserWindow.getAllWindows();
  if (windows.length === 0) {
    createWindow();
  } else {
    windows[0].focus();
  }
};

const createTray = () => {
  const tray = new Tray("src/assets/main/NewLogoHead.png");
  const contextMenu = Menu.buildFromTemplate([
    { label: "tymt 0.1.0", enabled: false },
    {
      label: "Open tymt",
      role: "window",
      accelerator: "Alt+T",
      click: () => openWindow(),
    },
    { type: "separator" },
    { label: "Exit", click: () => app.quit() },
  ]);
  tray.setToolTip("This is my application.");
  tray.setTitle("tymt");
  tray.setContextMenu(contextMenu);

  tray.on("click", () => openWindow());
};

const registerGlobalShortcut = () => {
  globalShortcut.register("Alt+T", () => openWindow());
};

