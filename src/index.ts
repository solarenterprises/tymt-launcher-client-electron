ipcMain.handle("download-file", async (event, { downloadLink, downloadPath }: IDownloadFile) => {
  const win = BrowserWindow.getFocusedWindow();

  win.webContents.downloadURL(downloadLink);

  const onDownload = () =>
    new Promise((resolve, reject) => {
      win.webContents.session.on("will-download", (event, item) => {
        // Set save path
        item.setSavePath(downloadPath);

        // Monitor progress
        item.on("updated", (event, state) => {
          if (state === "interrupted") {
            console.log("Download is interrupted but can be resumed");
          } else if (state === "progressing") {
            if (item.isPaused()) {
              console.log("Download is paused");
            } else {
              const progress = item.getReceivedBytes() / item.getTotalBytes();
              // const progress = item.getReceivedBytes() / 18578583;
              console.log("Download progress:", item.getReceivedBytes(), item.getTotalBytes());
              win.webContents.send("download-progress", progress * 100); // Send progress to renderer
            }
          }
        });

        // Download completed
        item.once("done", (event, state) => {
          if (state === "completed") {
            console.log("Download successful");
            resolve(true);
          } else {
            console.error("Download failed");
            reject(new Error("Download failed"));
          }
        });
      });
    });

  await onDownload();
});

ipcMain.handle("unzip-file", async (event, { fileLocation, installDir }: IUnzipFile) => {
  await ensureExistDir(installDir);
  await extractAsync(fileLocation, installDir);
});

ipcMain.handle("move-app-image-linux", async (event, { fileLocation, installDir }: IUnzipFile) => {
  const sourcePath = path.resolve(fileLocation);
  const fileName = path.basename(sourcePath);
  const destinationPath = path.join(installDir, fileName);

  // Ensure the parent directory exists
  const parentDir = path.dirname(destinationPath);
  ensureExistDir(parentDir);

  // Move the file
  await fs.rename(sourcePath, destinationPath);
});

ipcMain.handle("un-tar-bz2-macos", async (event, { fileLocation, installDir }: IUnzipFile) => {
  await ensureExistDir(installDir);
  await execAsync(`tar -xvjf "${fileLocation}" -C "${installDir}"`);
});

ipcMain.handle("set-permission", async (event, executablePath: string) => {
  if ((await fs.stat(executablePath)).isFile()) {
    await fs.chmod(executablePath, 0o755); // Set permissions to rwxr-xr-x
  }
});

ipcMain.handle("delete-file", (event, filePath: string) => shell.trashItem(filePath));

ipcMain.handle("read-dir", async (event, dirPath: string) => {
  try {
    return (await fs.stat(dirPath)).isDirectory();
  } catch (error) {
    return false;
  }
});

ipcMain.handle("open-dir", (event, dirPath: string) => shell.openPath(dirPath));

ipcMain.handle("delete-dir", (event, dirPath: string) => fs.rmdir(dirPath, { recursive: true }));

ipcMain.handle("run-url-args", async (event, { url, args }: IRunUrlArgs) => {
  const commandPath = url === "open" ? args[1] : url;
  const workingDirectory = path.dirname(commandPath);

  await execAsync(commandPath, { cwd: workingDirectory });
});

ipcMain.handle("open-link", (event, url: string) => shell.openExternal(url));

